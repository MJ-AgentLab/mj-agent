"""build_fidelity_attestations.py — PR-C0 fidelity attestation producer.

Epic #499 plan §2.7 item 9 / §2.8.5 / §5.7. Produces the three PR-C0 artifacts:

  build-coverage  the 13 renderer-generated coverage reports under
                  ``evidence/development-agent-v8/fidelity/coverage/``
  build-packet    the per-tranche reviewer packets that make the mandated
                  source-description -> discovery-summary trigger judgment
                  possible without an unaided full-text read
  build-index     the tracked signing index ``sdd/adapters/codex-skill-fidelity.yml``

Direction of trust (this is the whole point of the unit):

  * Coverage reports are MACHINE-GENERATED by the renderer
    (``skill_renderer.generate_coverage``) — plan §2.7 item 9. The independent
    closure check lives in ``check_fidelity_attestations.py``, which never
    imports that generator; this producer never imports the checker either.
  * ``build-index`` REFUSES to invent an approval. Every ``approval_binding``
    field must arrive verbatim from a real reviewer record via ``--bindings``;
    the producer only VERIFIES that the reviewer's ``reviewed_*`` digests equal
    the digests this tree actually computes. Author-filled verdicts are exactly
    what plan §2.7 forbids, so "no bindings" is an exit-2
    ``BLOCKED_PREREQUISITE``, never a default-approved index.

Candidate anchor: every digest is taken from GIT BLOB bytes at ``--rev``
(default = the PR-B merge commit that PR-P1b pinned). A Windows checkout is
CRLF under ``* text=auto``, so reading the worktree would publish digests that
Linux CI could never reproduce (plan follow-up F9). The rendered candidate
bytes are produced in memory and are deliberately NOT written into the
repository — PR-P1b Gate 1 published digests only.

Equivalent reuse (recorded per plan §3.3): the candidate render pipeline is
PR-P1b's ``run_codex_carrier_probe.build_candidate_render`` — owner PR-P1b,
interface ``(repo_root, rev, work_dir) -> CandidateRender``, pinned by
``tests/unit/test_fidelity_attestations_c0.py``. Re-implementing it here would
duplicate ~100 lines whose only correctness criterion is "produces the exact
bytes PR-P1b published".

Exit codes follow the repo-wide checker convention: 0 clean; 1 drift
(``build-coverage --check`` found a committed report that no longer matches a
fresh render); 2 unusable input / unmet prerequisite. Read-only w.r.t.
everything except its own declared output paths; no secrets; no network.
"""

